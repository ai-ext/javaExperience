import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderProfileDtoJourney } from './profile-dto-journey.mjs';

const root = new URL('../../', import.meta.url);
const source = fs.readFileSync(new URL('scenario/ch0-first-steps/0-4-dto-rules.md', root), 'utf8');
const markup = renderProfileDtoJourney(source);
const panel = (index) => markup.slice(markup.indexOf(`data-first-java-panel="${index}"`), markup.indexOf(`data-first-java-panel="${index + 1}"`) > -1 ? markup.indexOf(`data-first-java-panel="${index + 1}"`) : undefined);
assert.deepEqual([...markup.matchAll(/data-first-java-panel="(\d+)"/g)].map((match) => Number(match[1])), Array.from({ length: 20 }, (_, index) => index));
for (const term of ['ProfileController.java', 'POST /api/start/profile']) assert.ok(panel(0).includes(term));
for (const term of ['HTTP 200', 'HTTP 400', 'HTTP 500', 'static', 'Jackson', 'getter']) assert.ok(!panel(0).includes(term), `첫 장면에 ${term}가 없어야 합니다`);
for (const term of ['public record ProfileRequest(String name, int age)', 'public record ProfileResponse(String name, int age, boolean adult)', 'boolean adult = request.age() &gt;= 19;', 'ProfileController$ProfileRequest', 'tools.jackson.databind.exc.InvalidDefinitionException', 'Cannot map null into type int', 'HTTP 200 · 본문 {}', 'com.fasterxml.jackson.databind', 'Jackson 2.18.2 · 단독 실험']) assert.ok(markup.includes(term), `${term} 누락`);
assert.equal((markup.match(/data-first-java-request="/g) || []).length, 3);
for (const id of 'ABC') assert.ok(markup.includes(`data-first-java-request="${id}"`));
assert.equal((markup.match(/mockups-2026-10-16-batch39\//g) || []).length, 20);
assert.match(panel(5), /&quot;김자바&quot;/);
assert.match(panel(6), /&quot;이프론&quot;/);
assert.match(panel(7), /data-first-java-request="C"/);
assert.match(panel(11), /HTTP 500/);
assert.match(panel(14), /HTTP 400/);
assert.match(panel(15), /HTTP 200/);
assert.match(panel(16), /HTTP 200 · 본문 \{\}/);
const built = fs.readFileSync(new URL('scenario/ch0-first-steps/0-4-dto-rules.html', root), 'utf8');
for (const file of ['first-java-journey.css', 'annotation-journey.css', 'profile-dto-journey.css', 'first-java-journey.js']) assert.ok(built.includes(file));
assert.match(built, /class="first-java-original"/);
assert.equal((built.match(/data-first-java-panel="/g) || []).length, 20);
assert.equal((built.match(/class="api-request" data-request-id="/g) || []).length, 3);
const assets = JSON.parse(fs.readFileSync(new URL('docs/design/mockups-2026-10-16-batch39/asset-index.json', root), 'utf8'));
assert.equal(assets.images.length, 20);
for (const asset of assets.images) assert.ok(fs.existsSync(new URL(`docs/design/mockups-2026-10-16-batch39/${asset.file}`, root)));
console.log('0-4 20장면·첫 화면 경계·A/B/C·DTO 생성/응답·400/500/빈 JSON·Jackson 버전 경계 통과');
