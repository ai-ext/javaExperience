import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { renderP09Learning } from './p09-learning.mjs';
import { initP09Learning } from './p09-learning.js';
// 모바일에서는 시안의 참조 연결을 DOM으로 재배치해 값과 라벨을 크게 읽는다.
const mobilePage=new JSDOM(renderP09Learning(),{url:'https://learn.example/docs/knowledge/P09-java-syntax-basics.html'});
const mw=mobilePage.window,md=mw.document,ms=(s)=>md.querySelector(s);
let onMediaChange; const media={matches:true,addEventListener(type,handler){onMediaChange=handler;}};
mw.matchMedia=()=>media;
initP09Learning(md,mw);
assert.ok(ms('[data-p09-mobile-next]'),'모바일의 다음 버튼은 장면 선택 옆에 둔다');
ms('[data-p09-topic]').value='references';ms('[data-p09-topic]').dispatchEvent(new mw.Event('change',{bubbles:true}));
assert.ok(ms('[data-p09-stage-select]'),'모바일 장면은 긴 버튼 목록 대신 native select로 조작');
function mobileStage(id){ms('[data-p09-stage-select]').value=id;ms('[data-p09-stage-select]').dispatchEvent(new mw.Event('change',{bubbles:true}));}
mobileStage('mutation-copy');
assert.equal(ms('[data-p09-reference-mobile]').hidden,false);
assert.equal(md.querySelectorAll('[data-p09-ref-object]').length,1);
assert.equal(ms('[data-p09-ref-source="caller"]').dataset.refTarget,'A');
assert.equal(ms('[data-p09-ref-source="parameter"]').dataset.refTarget,'A');
assert.match(ms('[data-p09-ref-object="A"]').textContent,/Ada/);
mobileStage('reassignment-local');
assert.equal(md.querySelectorAll('[data-p09-ref-object]').length,2);
assert.equal(ms('[data-p09-ref-source="caller"]').dataset.refTarget,'A');
assert.equal(ms('[data-p09-ref-source="parameter"]').dataset.refTarget,'B');
assert.match(ms('[data-p09-ref-object="A"]').textContent,/Grace/);
assert.match(ms('[data-p09-ref-object="B"]').textContent,/Local only/);
assert.equal(ms('.p09-image-frame').hidden,true,'휴대폰에서는 같은 시안 관계를 DOM으로 재배치');
mobileStage('reassignment-return');
assert.equal(ms('[data-p09-ref-source="parameter"]'),null);
assert.match(ms('[data-p09-ref-object="B"]').textContent,/GC.*미정|수거 시점/);
assert.ok(ms('[data-p09-ref-object="B"]').classList.contains('p09-ref-unreachable'));
assert.equal(ms('[data-p09-mobile-next]').disabled,true);
mobileStage('reassignment-local');ms('[data-p09-mobile-next]').focus();ms('[data-p09-mobile-next]').click();
assert.equal(md.activeElement,ms('[data-p09-stage-select]'),'끝 장면에서 비활성화된 조작의 포커스를 장면 선택으로 이동');
ms('[data-p09-topic]').value='methods';ms('[data-p09-topic]').dispatchEvent(new mw.Event('change',{bubbles:true}));
mobileStage('static-call');
assert.match(ms('[data-p09-figure-label]').textContent,/좌우/,'긴 그림을 글자 축소 대신 좌우로 읽는 안내');
assert.ok(ms('.p09-image-window'),'확대할 구간을 담는 내부 창');
assert.equal(ms('.p09-image-frame').tabIndex,0,'확대한 그림은 키보드로도 이동 가능');
ms('[data-p09-zoom]').click();
media.matches=false;onMediaChange({matches:false});
ms('[data-p09-topic]').value='references';ms('[data-p09-topic]').dispatchEvent(new mw.Event('change',{bubbles:true}));
assert.equal(ms('[data-p09-reference-mobile]').hidden,true);
media.matches=true;onMediaChange({matches:true});
assert.equal(ms('[data-p09-reference-mobile]').hidden,false,'수동 확대를 바꿔도 화면 크기가 달라지면 참조 배치 갱신');
mw.close();
console.log('P09 모바일: native 장면 선택·공유 객체·분리 재할당·복귀 후 참조 소멸과 GC 미정 검사 통과');
