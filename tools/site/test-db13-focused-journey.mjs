import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderDb13FocusedJourney } from './db13-focused-journey.mjs';

const root=new URL('../../',import.meta.url);
const source=fs.readFileSync(new URL('scenario/db-query-journey/db-13-list-api-n-plus-one.md',root),'utf8');
const mission=fs.readFileSync(new URL('practice/MISSIONS.md',root),'utf8');
const markup=renderDb13FocusedJourney(source);
assert.deepEqual([...markup.matchAll(/data-db13-panel="([^"]+)"/g)].map((match)=>match[1]),['scenario','contract','request','path','loop','instrument','baseline','author-projection','tag-batch','collection','recheck','conclusion']);
const first=markup.slice(markup.indexOf('data-db13-panel="scenario"'),markup.indexOf('data-db13-panel="contract"'));
assert.match(first,/만들 것/);
assert.match(first,/직접 할 것/);
assert.match(first,/GET \/api\/boards\/dev\/posts\?size=5&amp;cursor=/);
assert.doesNotMatch(first,/1 \+ N|actual|authorNickname|SQL 수가 [0-9]+/);
for(const field of ['id','title','authorNickname','likeCount','commentCount','tags[]','publishedAt'])assert.ok(markup.includes(`<span>${field}</span>`));
assert.match(markup,/<code>content<\/code> · 목록 응답에서 제외/);
assert.match(mission,/GET \/api\/boards\/\{slug\}\/posts\?size=20&cursor=/);
const blocks=[...source.matchAll(/```(?:java|sql)\n([\s\S]*?)\n```/g)].map((match)=>match[1]);
assert.equal(blocks.length,3);
for(const block of blocks)assert.ok(markup.includes(block.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;')),'원문 Java/SQL을 그대로 보여야 한다');
assert.match(blocks[1],/p\.visibility = 'PUBLIC'/);
assert.match(markup,/:page_post_ids<\/code>는 Java\/JPA\/MyBatis에서 실제 ID 목록으로 펼쳐 바인딩/);
assert.match(markup,/실제 SQL 수가 아닙니다/);
assert.match(markup,/count SQL이 생략돼 큰 size의 문장 수가 더 적을 수도 있습니다/);
assert.equal((markup.match(/data-db13-record="/g)||[]).length,14);
assert.equal((markup.match(/data-db13-copy="/g)||[]).length,3);
const built=fs.readFileSync(new URL('scenario/db-query-journey/db-13-list-api-n-plus-one.html',root),'utf8');
for(const asset of ['first-db-journey.css','db13-focused-journey.css','db13-focused-journey.js'])assert.ok(built.includes(asset));
assert.equal((built.match(/data-db13-panel="/g)||[]).length,12);
assert.match(built,/class="db13-original"/);
console.log('DB-13 열두 장면·M1 계약·원문 코드·측정값 경계 검사 통과');
