import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderMemberDebugJourney } from './member-debug-journey.mjs';

const root = new URL('../../', import.meta.url);
const source = fs.readFileSync(new URL('scenario/ch0-first-steps/0-5-read-stack-trace.md', root), 'utf8');
const markup = renderMemberDebugJourney(source);
const panel = (index) => markup.slice(markup.indexOf(`data-first-java-panel="${index}"`), markup.indexOf(`data-first-java-panel="${index + 1}"`) > -1 ? markup.indexOf(`data-first-java-panel="${index + 1}"`) : undefined);
assert.deepEqual([...markup.matchAll(/data-first-java-panel="(\d+)"/g)].map((match) => Number(match[1])), Array.from({ length: 18 }, (_, index) => index));
for (const term of ['MemberController.java', 'GET /api/start/members/3']) assert.ok(panel(0).includes(term));
for (const term of ['HTTP 200', 'HTTP 404', '500', 'NullPointerException', 'Caused by', 'Map.of', 'IntelliJ']) assert.ok(!panel(0).includes(term), `첫 장면에 ${term}가 없어야 합니다`);
for (const term of ['Map.of(1L, &quot;kimjava&quot;, 2L, &quot;leespring&quot;)', 'MemberController.java:20', 'ResponseStatusException(HttpStatus.NOT_FOUND', 'start.greating', 'Map.of(&quot;id&quot;, id, &quot;nickname&quot;, nickname)', '/api/start/members/abc']) assert.ok(markup.includes(term), `${term} 누락`);
assert.match(panel(4), /data-first-java-request="A"/);
assert.match(panel(5), /data-first-java-request="B"/);
assert.match(panel(5), /C2의 기대값 404는 고친 뒤 기준/);
assert.match(panel(11), /data-first-java-request="B"/);
assert.match(panel(11), /500 → 수정 후 404/);
assert.match(panel(13), /ConfigController를 만들 필요는 없습니다/);
assert.match(panel(15), /지금 파일을 바꿀 필요는 없습니다/);
assert.equal((markup.match(/mockups-2026-10-16-batch40\//g) || []).length, 18);
const assets = JSON.parse(fs.readFileSync(new URL('docs/design/mockups-2026-10-16-batch40/asset-index.json', root), 'utf8'));
assert.equal(assets.images.length, 18);
for (const asset of assets.images) assert.ok(fs.existsSync(new URL(`docs/design/mockups-2026-10-16-batch40/${asset.file}`, root)));
const built = fs.readFileSync(new URL('scenario/ch0-first-steps/0-5-read-stack-trace.html', root), 'utf8');
for (const file of ['first-java-journey.css', 'annotation-journey.css', 'member-debug-journey.css', 'first-java-journey.js']) assert.ok(built.includes(file));
assert.match(built, /class="first-java-original"/);
assert.equal((built.match(/data-first-java-panel="/g) || []).length, 18);
assert.equal((built.match(/class="api-request" data-request-id="/g) || []).length, 2);
console.log('0-5 18장면·첫 화면 경계·A/B 재요청·500→404·로그/선택 심화 원문 계약 통과');
