import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { renderHomeServicePreview } from './home-service-preview.mjs';
import { initHomeServicePreview } from './home-service-preview.js';

const dom = new JSDOM(renderHomeServicePreview(), { url: 'https://learn.example/' });
const { document: doc } = dom.window;
const $ = (selector) => doc.querySelector(selector);
dom.window.fetch = () => { throw Error('예시 게시판은 서버에 요청하지 않는다'); };
Object.defineProperty(dom.window, 'localStorage', { get() { throw Error('예시 게시판은 진도를 저장하지 않는다'); } });
initHomeServicePreview(doc);
assert.equal(doc.querySelectorAll('[data-service-post]').length, 3);
assert.match($('.home-service-section').textContent, /완성 모습 예시/);
assert.match($('[data-service-detail-title]').textContent, /처음 만든 게시글/);
$('[data-service-post="2"]').click();
assert.equal($('[data-service-detail-title]').textContent, 'DTO와 Entity, 이제 구분이 돼요');
assert.equal(doc.activeElement, $('[data-service-detail-title]'));
$('[data-service-write]').click();
assert.equal($('[data-service-compose]').hidden, false);
assert.equal(doc.activeElement, $('#home-service-title'));
$('[data-service-form]').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal($('#home-service-title').getAttribute('aria-invalid'), 'true');
assert.match($('#home-service-title-error').textContent, /제목/);
$('#home-service-title').value = '<img src=x onerror=alert(1)>';
$('[data-service-form]').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal($('#home-service-content').getAttribute('aria-invalid'), 'true');
assert.equal(doc.activeElement, $('#home-service-content'));
$('#home-service-content').value = '첫 줄\n두 번째 줄';
$('[data-service-form]').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(doc.querySelectorAll('[data-service-post]').length, 4);
assert.equal($('[data-service-detail-title]').textContent, '<img src=x onerror=alert(1)>');
assert.equal($('[data-service-detail-title]').children.length, 0);
assert.equal($('[data-service-detail-content]').textContent, '첫 줄\n두 번째 줄');
assert.equal($('[data-service-detail]').hidden, false);
assert.equal($('[data-service-compose]').hidden, true);
assert.match($('[data-service-status]').textContent, /서버/);
$('[data-service-back]').click();
assert.equal($('.home-service-board').dataset.serviceMode, 'list');
assert.equal(doc.activeElement, $('[data-service-post="4"]'));
$('[data-service-write]').click(); $('#home-service-title').value = '작성 중';
$('[data-service-cancel]').click();
$('[data-service-write]').click();
assert.equal($('#home-service-title').value, '작성 중', '취소 시 임시 입력을 보존한다');
initHomeServicePreview(doc);
assert.equal(doc.querySelectorAll('[data-service-post]').length, 4, '중복 초기화가 예시 글을 지우지 않는다');
dom.window.close();
console.log('완성 서비스 미리보기: 목록·상세·작성·빈 입력·포커스·사용자 문자열 안전·진도와 격리 통과');
