  initLearning(exercise.doc, exercise.window);
  const panels = [...exercise.doc.querySelector(task.journey).querySelectorAll(`[${task.panel}]`)];
  const target = panels[1].getAttribute(task.panel);
  const go = [...exercise.doc.querySelector(task.journey).querySelectorAll(`[${task.go}]`)].find((el) => el.getAttribute(task.go) === target);
