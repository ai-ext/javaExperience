const root = new URL('../../', import.meta.url);
function page(file = 'index.html', saved) {
  const dom = new JSDOM(file === 'index.html' ? `<main>${renderHomeVisual(root.pathname, new URL('README.md',root).pathname, '<h2 id="javaexperience">실행 안내</h2>')}</main><script data-home-controller data-home-root="index.html" src="tools/site/home-learning.bundle.js"></script>` : fs.readFileSync(new URL(file, root), 'utf8'), { url: `https://learn.example/${file}`, runScripts: 'outside-only' });
  const { window } = dom;
  window.scrollTo = () => {};
  window.HTMLElement.prototype.scrollIntoView = () => {};
  window.HTMLDialogElement.prototype.showModal = function () { this.open = true; this.querySelector('button,input')?.focus(); };
  window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event('close')); };
  // 페이지 이동은 검증된 href로 따로 확인한다. DOM 테스트는 실제 브라우저 렌더를 대체하지 않는다.
  window.document.addEventListener('click', (event) => { if (event.target.closest('a')) event.preventDefault(); });
  window.fetch = () => { throw Error('홈 예시가 서버에 요청하면 안 됩니다'); };
  if (saved) window.localStorage.setItem(PROGRESS_KEY, saved);
  return { window, doc: window.document, $: (selector) => window.document.querySelector(selector), close: () => window.close() };
}
