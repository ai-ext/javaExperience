  const stored = exercise.window.localStorage.getItem(PROGRESS_KEY);
  assert.equal(JSON.parse(stored).records[id].scene.value, target, `${id} 장면 저장`);
  exercise.close();
  const back = page(task.href, stored);
  back.window.eval(fs.readFileSync(new URL(`tools/site/${script}`, root), 'utf8'));
  initLearning(back.doc, back.window);
  assert.equal([...back.doc.querySelector(task.journey).querySelectorAll(`[${task.panel}]`)].find((el) => el.getAttribute(task.panel) === target).hidden, false, `${id} 장면 복원`);
