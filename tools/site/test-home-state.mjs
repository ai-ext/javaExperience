import assert from 'node:assert/strict';
import { TASKS, PROGRESS_KEY, readProgress, startTask, saveScene, completeTask, reopenTask, chooseStart, homeView } from './home-state.mjs';
const memory = new Map();
const storage = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
assert.equal(homeView(readProgress(storage)).mode, 'first');
assert.equal(homeView(readProgress(storage)).previewingSelection, false);
assert.equal(homeView(readProgress(storage)).returnTask, null);
assert.equal(homeView(readProgress(storage)).returnRecord, null);
const firstSelection = chooseStart(readProgress(storage), 'DB-01', storage);
assert.equal(homeView(firstSelection).task.id, 'DB-01', '첫 방문에서도 적용한 시작점을 표시');
assert.equal(homeView(firstSelection).mode, 'first');
assert.equal(firstSelection.active, null, '시작점 적용은 과제 시작이 아님');
assert.equal(firstSelection.pendingStart, null);
let state = startTask(readProgress(storage), '0-1', storage);
state = saveScene(state, '0-1', { attribute: 'data-first-java-panel', value: '4', label: 'new로 객체 만들기' }, storage);
assert.equal(homeView(readProgress(storage)).task.id, '0-1');
assert.equal(homeView(readProgress(storage)).record.scene.value, '4');
const selected = chooseStart(state, '1-1', storage);
assert.equal(selected.active, '0-1', '시작점 선택만으로 진행 중 과제를 덮어쓰지 않음');
assert.equal(homeView(selected).task.id, '1-1', '적용하면 큰 카드와 미리보기용 과제가 즉시 바뀜');
assert.equal(homeView(selected).mode, 'selection');
assert.equal(homeView(selected).previewingSelection, true);
assert.equal(homeView(selected).record, null, '아직 시작하지 않은 선택 과제의 진도를 만들지 않음');
assert.equal(homeView(selected).next.id, '1-2', '다음 과제도 선택한 과제 기준');
assert.equal(homeView(selected).returnTask.id, '0-1');
assert.equal(homeView(selected).returnRecord.scene.value, '4', '기존 작업 위치는 별도 이어하기에서 복원');
assert.deepEqual(selected.records['0-1'], state.records['0-1']);
assert.equal(homeView(readProgress(storage)).task.id, '1-1', '새로고침 후에도 적용한 시작점을 유지');
assert.equal(homeView(readProgress(storage)).returnRecord.scene.value, '4');
const selectedWhileLearning = saveScene(selected, '0-1', { attribute: 'data-first-java-panel', value: '5', label: 'JSON으로 응답 확인' }, storage);
assert.equal(homeView(selectedWhileLearning).task.id, '1-1', '기존 학습 탭의 이동이 선택한 카드를 되돌리지 않음');
assert.equal(homeView(selectedWhileLearning).returnRecord.scene.value, '5', '기존 학습 탭의 최신 위치도 보존');
const reselected = chooseStart(selected, 'DB-01', storage);
assert.equal(homeView(reselected).task.id, 'DB-01', '시작점을 다시 고르면 새 선택을 표시');
assert.equal(homeView(reselected).returnTask.id, '0-1', '재선택해도 원래 진행 과제를 보존');
const originalSelected = chooseStart(reselected, '0-1', storage);
assert.equal(originalSelected.pendingStart, null, '진행하던 과제를 다시 고르면 선택 안내 해제');
assert.equal(homeView(originalSelected).mode, 'resume');
assert.equal(homeView(originalSelected).returnTask, null);
assert.equal(homeView(originalSelected).record.scene.value, '4');
assert.equal(saveScene(selected, '1-1', { value: 'other' }, storage).active, '0-1');
const startedSelection = startTask(selected, '1-1', storage);
assert.equal(startedSelection.active, '1-1', '시작 버튼을 눌렀을 때만 진행 과제 전환');
assert.equal(startedSelection.pendingStart, null);
assert.equal(homeView(startedSelection).mode, 'resume');
assert.equal(homeView(startedSelection).previewingSelection, false);
assert.deepEqual(startedSelection.records['0-1'], state.records['0-1']);
assert.equal(startTask(startedSelection, '0-1', storage).records['0-1'].scene.value, '4');
state = completeTask(selected, '0-1', storage);
assert.equal(homeView(state).mode, 'selection', '별도 탭에서 기존 과제를 완료해도 선택 카드 유지');
assert.equal(homeView(state).returnRecord.status, 'complete');
const completedView = chooseStart(state, '0-1', storage);
assert.equal(homeView(completedView).mode, 'complete');
assert.equal(homeView(completedView).next.id, '0-2');
assert.equal(homeView(reopenTask(completedView, '0-1', storage)).mode, 'resume');
const completedSelection = chooseStart(completedView, 'DB-01', storage);
assert.equal(homeView(completedSelection).mode, 'selection', '완료 후에도 새 시작점을 바로 확인');
assert.equal(homeView(completedSelection).returnRecord.status, 'complete');
const previousSelection = chooseStart(startTask(startedSelection, 'DB-01', storage), '1-1', storage);
assert.equal(homeView(previousSelection).record.status, 'in-progress', '이미 진행했던 과제를 선택하면 기존 기록 전달');
state = startTask(state, '0-2', storage);
assert.equal(state.records['0-1'].status, 'complete');
assert.equal(state.records['0-2'].status, 'in-progress');
assert.equal(TASKS['1-1'].api, 'POST /api/posts');
assert.match(TASKS['1-1'].goal, /success/);
assert.match(TASKS['1-2'].goal, /201/);
assert.throws(() => startTask(state, 'https://evil.invalid', storage));
assert.equal(readProgress({ getItem: () => '{broken' }).active, null);
const readStored = (overrides) => readProgress({ getItem: () => JSON.stringify({ ...selected, ...overrides }) });
assert.equal(readStored({ pendingStart: 'DB-01' }).pendingStart, null, '선택값과 다른 대기 과제는 무시');
assert.equal(readStored({ active: null }).pendingStart, null, '기존 진행 과제가 없으면 대기값 무시');
assert.equal(readStored({ active: '1-1', records: {} }).pendingStart, null, '손상된 진행 과제와 대기값을 함께 무시');
assert.equal(readStored({ selected: '0-1', pendingStart: '0-1' }).pendingStart, null, '진행 과제와 같은 대기값 무시');
assert.equal(readStored({ pendingStart: 'bogus' }).pendingStart, null);
assert.equal(readStored({ pendingStart: null }).pendingStart, null);
assert.equal(homeView(readStored({ pendingStart: 'DB-01' })).task.id, '0-1');
assert.deepEqual(JSON.parse(memory.get(PROGRESS_KEY)).records['0-1'].scene, state.records['0-1'].scene);
assert.equal(readProgress({ getItem: () => '{"version":1,"active":"bogus","selected":"bogus","records":[]}' }).active, null);
assert.equal(readProgress({ getItem: () => '{"version":1,"active":"0-1","records":{"0-1":{"status":"in-progress","scene":{"attribute":"onclick","value":"evil"}}}}' }).records['0-1'].scene, null);
const denied = { getItem() { throw Error('denied'); }, setItem() { throw Error('denied'); } };
assert.equal(startTask(readProgress(denied), '0-1', denied).active, '0-1');
console.log('홈 상태: 시작점 즉시 적용·기존 진도 보존·재방문·시작·위치·수동 완료·손상/차단 저장소 검사 통과');
