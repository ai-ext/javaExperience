import { readHistoricalGeneratedFixture } from './learning-source-baseline.mjs';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { JSDOM } from 'jsdom';

const html = readFileSync(new URL('../../docs/knowledge/D11-web-security-basics.html', import.meta.url), 'utf8');
const originalHtml = readHistoricalGeneratedFixture(new URL('../../', import.meta.url), 'D11');
const currentDom = new JSDOM(html, { url: 'https://javaexperience.test/docs/knowledge/D11-web-security-basics.html', runScripts: 'outside-only' });
const originalDom = new JSDOM(originalHtml);
const doc = currentDom.window.document;
const original = originalDom.window.document;
assert.equal(doc.querySelectorAll('[data-d11-learning]').length, 1);
assert.equal(doc.querySelectorAll('#d11-original').length, 1);
assert.equal(doc.querySelectorAll('.d11-legacy').length, 1);
assert.equal(doc.querySelectorAll('.knowledge-chapters').length, 1);
// 절 전환의 hidden 속성만 배치 상태로 제외한다. 나머지 원문 DOM·코드·앵커 대조는 그대로 유지한다.
const sourceWithoutSelection = node => {
  const copy = node.cloneNode(true);
  copy.querySelectorAll('details.knowledge-chapter').forEach(chapter => chapter.removeAttribute('hidden'));
  return copy.outerHTML;
};
assert.equal(sourceWithoutSelection(doc.querySelector('.knowledge-reader-original #d11-original .knowledge-chapters')), sourceWithoutSelection(original.querySelector('.knowledge-chapters')));
assert.equal(doc.querySelector('.d11-legacy .knowledge-page-map').outerHTML, original.querySelector('.knowledge-page-map').outerHTML);
assert.equal(doc.querySelectorAll('[id]').length, new Set([...doc.querySelectorAll('[id]')].map(node => node.id)).size);
assert.equal(doc.querySelector('[data-d11-topic]').value, 'object-ownership');
assert.equal(doc.querySelector('[data-d11-stage-select]'), null);
assert.equal(doc.querySelector('[data-d11-mobile-prev]'), null);
assert.equal(doc.querySelector('link[href*="p09-learning.css"]') !== null, true);
assert.equal(doc.querySelector('link[href*="d11-learning.css"]') !== null, true);
assert.equal(doc.querySelector('script[src*="d11-learning.bundle.js"]') !== null, true);

const dataScript = doc.querySelector('[data-d11-data]');
assert.ok(dataScript);
const payload = JSON.parse(dataScript.textContent);
assert.equal(payload.lessons.length, 12);
assert.equal(payload.lessons.flatMap(lesson => lesson.stages).length, 38);
assert.equal(payload.assetRoot, '../design/d11-2026-10-25/');
const d11Css = readFileSync(new URL('./d11-learning.css', import.meta.url), 'utf8');
assert.doesNotMatch(d11Css, /@media|linear-gradient|box-shadow|data-d11-stage-select/);
assert.match(d11Css, /\.p09-value-sheet dd\{[^}]*font-size:17px/);
assert.doesNotMatch(d11Css, /\.p09-code-sheet code\{[^}]*font-size:(?:[0-9]|1[0-3])px/);
assert.equal(createHash('sha256').update(readFileSync(new URL('../../docs/knowledge/D11-web-security-basics.md', import.meta.url))).digest('hex'), 'a9ba3c0109c24d61fcfbaf0e013ab2b90cee5dceac5a8432326f4bc7f63e2fba');
assert.equal(doc.querySelector('.d11-legacy').closest('[data-kr-reading]'), null);
assert.match(html, /기존 전체 웹 보안 개념 지도 보기/);
assert.match(html, /원문 전체 · 코드·위험 경계·자가점검 보기/);

const reader = readFileSync(new URL('./knowledge-reader.js', import.meta.url), 'utf8');
const d11Bundle = readFileSync(new URL('./d11-learning.bundle.js', import.meta.url), 'utf8');
const visibleHeadings = mode => [...doc.querySelectorAll('h1')].filter(node => {
  if (node.classList.contains('kr-source-title')) return false;
  if (node.closest('[data-kr-reading]') && node.closest('[data-kr-reading]').hidden) return false;
  if (node.classList.contains('kr-reading-title')) return mode === 'read';
  if (node.closest('.kr-toolbar-title')) return mode === 'scene';
  return !node.closest('details:not([open])');
});
currentDom.window.eval(d11Bundle);
currentDom.window.eval(reader);
doc.dispatchEvent(new currentDom.window.Event('DOMContentLoaded', { bubbles: true }));
const readerRoot = doc.querySelector('[data-knowledge-reader]');
assert.equal(readerRoot.dataset.krMode, 'scene');
assert.equal(doc.querySelector('[data-d11-learning]').dataset.stage, 'own-order');
assert.equal(doc.querySelectorAll('[data-d11-stage]').length, 4);
assert.deepEqual(visibleHeadings('scene').map(node => node.textContent.trim()), ['D11. 웹 보안 기초']);
doc.querySelector('[data-d11-topic]').value = 'sql-boundary';
doc.querySelector('[data-d11-topic]').dispatchEvent(new currentDom.window.Event('change', { bubbles: true }));
doc.querySelector('[data-d11-stage="sort-rejected"]').click();
assert.equal(doc.querySelector('[data-d11-learning]').dataset.stage, 'sort-rejected');
doc.querySelector('[data-kr-mode="read"]').click();
assert.equal(readerRoot.dataset.krMode, 'read');
assert.equal(doc.querySelector('[data-d11-learning]').dataset.stage, 'sort-rejected');
assert.deepEqual(visibleHeadings('read').map(node => node.textContent.trim()), ['D11. 웹 보안 기초']);
doc.querySelector('[data-kr-mode="scene"]').click();
assert.equal(readerRoot.dataset.krMode, 'scene');
assert.equal(doc.querySelector('[data-d11-learning]').dataset.stage, 'sort-rejected');
assert.deepEqual(visibleHeadings('scene').map(node => node.textContent.trim()), ['D11. 웹 보안 기초']);
