import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderRequestPlacesJourney } from './request-places-journey.mjs';

const root = new URL('../../', import.meta.url);
const source = fs.readFileSync(new URL('scenario/ch0-first-steps/0-3-request-four-places.md', root), 'utf8');
const markup = renderRequestPlacesJourney(source);
const panel = (index) => markup.slice(markup.indexOf(`data-first-java-panel="${index}"`), markup.indexOf(`data-first-java-panel="${index + 1}"`) > -1 ? markup.indexOf(`data-first-java-panel="${index + 1}"`) : undefined);
assert.deepEqual([...markup.matchAll(/data-first-java-panel="(\d+)"/g)].map((match) => Number(match[1])), Array.from({ length: 21 }, (_, index) => index));
for (const term of ['EchoController.java', 'POST /api/start/echo/7?q=spring']) assert.ok(panel(0).includes(term));
for (const term of ['200', '400', '415', 'DTO', 'Map', 'CORS', 'fromBody']) assert.ok(!panel(0).includes(term), `첫 장면에 ${term}가 없어야 합니다`);
assert.equal((markup.match(/data-first-java-request="/g) || []).length, 4);
for (const id of 'ABCD') assert.ok(markup.includes(`data-first-java-request="${id}"`));
assert.equal((markup.match(/mockups-2026-10-16-batch38\//g) || []).length, 21);
for (const term of ['public record EchoBody(String title, List&lt;String&gt; tags)', 'public record EchoResponse(Long fromPath, String fromQuery, String fromHeader, Object fromBody)', '@PathVariable Long id', '@RequestParam String q', '@RequestHeader(&quot;X-Client&quot;) String client', '@RequestBody Map&lt;String, Object&gt; body', 'MissingRequestHeaderException', 'MethodArgumentTypeMismatchException', 'HttpMessageNotReadableException']) assert.ok(markup.includes(term), `${term} 누락`);
assert.match(panel(8), /&quot;extra&quot;/);
assert.doesNotMatch(panel(11), /&quot;extra&quot;/);
assert.match(panel(14), /data-first-java-request="C"/);
assert.match(panel(15), /data-first-java-request="D"/);
assert.doesNotMatch(panel(19), /HTTP 400|HTTP 415/);
const built = fs.readFileSync(new URL('scenario/ch0-first-steps/0-3-request-four-places.html', root), 'utf8');
for (const file of ['first-java-journey.css', 'annotation-journey.css', 'request-places-journey.css', 'first-java-journey.js']) assert.ok(built.includes(file));
assert.match(built, /class="first-java-original"/);
assert.equal((built.match(/data-first-java-panel="/g) || []).length, 21);
assert.equal((built.match(/class="api-request" data-request-id="/g) || []).length, 4);
assert.match(built, /id="scenario-base-url"/);
const assets = JSON.parse(fs.readFileSync(new URL('docs/design/mockups-2026-10-16-batch38/asset-index.json', root), 'utf8'));
assert.equal(assets.images.length, 21);
for (const asset of assets.images) assert.ok(fs.existsSync(new URL(`docs/design/mockups-2026-10-16-batch38/${asset.file}`, root)));
console.log('0-3 21장면·첫 화면 경계·네 입력 자리·Map/DTO·요청 A~D·400/415/CORS 계약 통과');
