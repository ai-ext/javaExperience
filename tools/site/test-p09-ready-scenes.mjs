assert.match($('[data-p09-note]').textContent,/미실행/);
assert.match($('[data-p09-state]').textContent,/DB 저장이 예제에 없음/);
topic('signature');stage('class-qualified-call');
assert.match($('[data-p09-state]').textContent,/Invoice 클래스/);
assert.match($('[data-p09-state]').textContent,/thisstatic 문맥에 없음/);
stage('void-early');assert.match($('[data-p09-state]').textContent,/paid=true 경로즉시 종료/);
topic('arithmetic');
for(const [id,value] of [['subtotal','3600'],['discounted','3240'],['precedence','14'],['left-to-right','19']]){stage(id);assert.ok($('[data-p09-state]').textContent.includes(value),id+' 원문 실행값 '+value);}
topic('methods');stage('format-inner');
assert.equal($('[data-p09-code] mark').textContent,'format(name)','내부 호출에 해당하는 식을 강조');
stage('format-repeat');assert.equal($('[data-p09-code] mark').textContent,'.repeat(count)','같은 줄에서도 현재 연산의 강조가 바뀜');
assert.match($('[data-p09-state]').textContent,/"Hello, Hi! Hello, Hi! "/);
topic('varargs');stage('varargs-empty');assert.match($('[data-p09-state]').textContent,/배열 길이0/);assert.match($('[data-p09-state]').textContent,/출력없음/);
const topicControl=$('[data-p09-topic]');topicControl.focus();topic('file');
assert.equal(d.activeElement,topicControl,'질문 선택 후 focus 유지');
stage('package');$('[data-p09-stage="package"]').focus();
$('[data-p09-stages]').dispatchEvent(new w.KeyboardEvent('keydown',{key:'End',bubbles:true}));
assert.equal(d.activeElement.dataset.p09Stage,'filename');
assert.equal($('[data-p09-title]').textContent,'패키지와 위치','방향키는 포커스만 옮김');
d.activeElement.click();assert.equal($('[data-p09-title]').textContent,'공개 클래스와 파일명');
assert.ok($('[data-p09-zoom]'),'선택 구간을 확대해 읽을 수 있는 조작');
assert.equal($('[data-p09-zoom]').getAttribute('aria-pressed'),'false');
$('[data-p09-zoom]').click();
assert.equal($('[data-p09-zoom]').getAttribute('aria-pressed'),'true');
assert.equal($('.p09-image-frame').dataset.zoom,'true');
assert.equal($('[data-p09-focus]').hidden,true,'확대 구간에는 중복 테두리를 그리지 않음');
assert.match($('[data-p09-image]').style.transform,/translate/);
$('[data-p09-zoom]').click();
assert.equal($('.p09-image-frame').dataset.zoom,'false');
for(const [id,a] of Object.entries(P09_ASSETS)){
 const file=fs.readFileSync(new URL('../../docs/design/p09-2026-10-20/images/'+a.file,import.meta.url));
 assert.equal(rasterDimensions(file).format,'jpeg',id+' 실제 JPG');
 assert.equal(rasterDimensions(file).width,a.width,id+' 실제 너비');assert.equal(rasterDimensions(file).height,a.height,id+' 실제 높이');
}
