topic('variables');stage('local');
assert.match($('[data-p09-state]').textContent,/retryCount0/);
assert.match($('[data-p09-state]').textContent,/attempt1/);
stage('scope-end');assert.match($('[data-p09-state]').textContent,/범위 종료/);
topic('greeting');stage('greeting-constructor');
assert.match($('[data-p09-state]').textContent,/Hello, Ada/);
assert.doesNotMatch($('[data-p09-state]').textContent,/Grace|Local only|김자바|nameLength/,'같은 이름인 홈 Greeting 데이터를 혼합하지 않음');
