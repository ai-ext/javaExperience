import assert from 'node:assert/strict';
import fs from 'node:fs';
import { renderDb07FocusedJourney } from './db07-focused-journey.mjs';

const root = new URL('../../', import.meta.url);
const source = fs.readFileSync(new URL('scenario/db-query-journey/DB-07-same-api-five-query-styles.md', root), 'utf8');
const mission = fs.readFileSync(new URL('practice/MISSIONS.md', root), 'utf8');
const markup = renderDb07FocusedJourney(source);
assert.deepEqual([...markup.matchAll(/data-db07-panel="([^"]+)"/g)].map((match) => match[1]),
  ['scenario', 'contract', 'baseline', 'one-method', 'derived', 'jpql', 'native', 'mybatis', 'querydsl', 'tags', 'compare', 'logs', 'cursor']);
const first = markup.slice(markup.indexOf('data-db07-panel="scenario"'), markup.indexOf('data-db07-panel="contract"'));
assert.match(first, /만들 것/);
assert.match(first, /직접 확인할 것/);
assert.doesNotMatch(first, /145|PostListRow|Top20|QueryDSL|SQL 복사/);
for (const field of ['id', 'title', 'authorNickname', 'likeCount', 'commentCount', 'tags[]', 'publishedAt']) assert.ok(markup.includes(`<span>${field}</span>`));
assert.match(markup, /<code>content<\/code>는 목록 응답에 없습니다/);
assert.match(mission, /145, 144, 143, 140, 138/);
assert.equal((markup.match(/data-db07-method="/g) || []).length, 5);
assert.equal((markup.match(/data-db07-record="/g) || []).length, 5);
const sections = [...source.matchAll(/<details>\s*<summary>(.*?)<\/summary>([\s\S]*?)<\/details>/g)].map((match) => match[2]);
assert.equal(sections.length, 5);
const snippets = sections.map((body) => [...body.matchAll(/```(?:java|xml)\n([\s\S]*?)\n```/g)].map((match) => match[1]));
const escapeHtml = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const commonSql = source.match(/```sql\n([\s\S]*?)\n```/)?.[1];
assert.ok(commonSql && markup.includes(escapeHtml(commonSql)), '공통 기준 SQL을 별도 장면에 원문 그대로 표시해야 한다');
for (const snippet of [snippets[0][0], snippets[1][1], snippets[2][0], snippets[3][1], snippets[4][0]]) assert.ok(markup.includes(escapeHtml(snippet)), '원문 코드 조각을 그대로 사용해야 한다');
assert.match(markup, /findTop20By/);
assert.match(markup, /PageRequest\.of\(0, 20\)/);
assert.match(markup, /nativeQuery=true/);
assert.match(markup, /#\{slug\}/);
assert.match(markup, /\$\{slug\}/);
assert.match(markup, /QPost는 L14 OpenFeign QueryDSL overlay/);
assert.match(markup, /opaque cursor/);
const built = fs.readFileSync(new URL('scenario/db-query-journey/DB-07-same-api-five-query-styles.html', root), 'utf8');
for (const asset of ['first-db-journey.css', 'db07-focused-journey.css', 'db07-focused-journey.js']) assert.ok(built.includes(asset));
assert.equal((built.match(/data-db07-panel="/g) || []).length, 13);
assert.match(built, /class="db07-original"/);
assert.match(built, /완료 확인/);
console.log('DB-07 열세 장면·원문 다섯 구현·M1/overlay/cursor 경계 검사 통과');
