import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { NEW_SCENES, renderHomeNewVisual } from './home-new-visual.mjs';
import { initHomeNewVisual } from './home-new-visual.js';
const dom = new JSDOM(renderHomeNewVisual(), { url: 'https://learn.example/index.html' });
const doc = dom.window.document;
initHomeNewVisual(doc);
const $ = (selector) => doc.querySelector(selector);
assert.equal(NEW_SCENES.length, 5);
assert.equal($('[data-object-count]').textContent, '이 예제의 Greeting 객체 0개');
assert.equal($('[data-object-previous]').disabled, true);
$('[data-object-next]').click();
assert.equal($('[data-object-count]').textContent, '이 예제의 Greeting 객체 1개');
assert.match($('[data-object-code]').textContent, /new Greeting/);
assert.equal($('[data-object-card]').hidden, false);
$('[data-object-scene="3"]').click();
assert.match($('[data-object-caption]').textContent, /참조/);
assert.match($('[data-object-reference]').textContent, /greeting.*same/);
assert.equal($('[data-object-second]').hidden, true);
$('[data-object-scene="4"]').click();
assert.equal($('[data-object-count]').textContent, '이 예제의 Greeting 객체 2개');
assert.equal($('[data-object-second]').hidden, false);
assert.equal($('[data-object-next]').disabled, true);
assert.match($('[data-object-image]').getAttribute('src'), /new-05-another-v2\.jpg$/);
assert.match($('[data-object-image]').alt, /another/);
assert.equal($('[data-object-open-image]').getAttribute('href'), $('[data-object-image]').getAttribute('src'));
assert.match($('[data-object-code]').textContent, /Greeting same = greeting;/);
assert.match($('[data-object-code]').textContent, /Greeting another = new Greeting/);
$('[data-object-previous]').click();
assert.equal($('[data-object-second]').hidden, true);
$('[data-object-scene="3"]').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true, cancelable: true }));
assert.equal($('[data-object-scene="2"]').getAttribute('aria-pressed'), 'true');
assert.equal(doc.activeElement, $('[data-object-scene="2"]'));
assert.match($('[data-object-caption]').textContent, /DB/);
assert.equal($('[data-object-image]').getAttribute('width'), '1536');
assert.equal($('[data-object-image]').getAttribute('height'), '1024');
dom.window.close();
console.log('new 시각 설명: 5개 이미지/장면·코드·객체 수·참조·이전/다음·키보드 검사 통과');
